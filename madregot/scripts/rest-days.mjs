#!/usr/bin/env node
// Writes madregot/shared/restDays.js from the Hebcal REST API (Hebcal.com, CC BY 4.0): Yom Tov, the national memorial
// days and Tish'a B'Av in Israel, one call per school year, 1 September 2026 to 31 August 2031 (STUDENT-5).
//
//   node madregot/scripts/rest-days.mjs            fetch, check and write the file
//   node madregot/scripts/rest-days.mjs --check    fetch and check only; print what would be written
//
// It needs network access to www.hebcal.com and Node 18 or later (global fetch). No packages.
// It fails, and writes nothing, if Hebcal's answer lacks any of the twelve dates verified on 10 November 2026, or
// if any request fails.
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const FIRST_YEAR = 2026; // school years 2026-27 … 2030-31
export const YEARS = 5;
export const API = 'https://www.hebcal.com/hebcal';

/** Exact Hebcal titles (from mod=on) of the memorial days that are quiet. Other modern days (Sigd, Family Day…) are not. */
export const MEMORIAL_TITLES = ['Yom HaShoah', 'Yom HaZikaron', 'Swords of Iron War Memorial Day'];
/** Tish'a B'Av (from maj=on, without yomtov); "(observed)" when it moves off Shabbat to Sunday. */
export const FAST_TITLES = ["Tish'a B'Av", "Tish'a B'Av (observed)"];
/** Hebcal writes apostrophes as U+2019 ("Tish’a B’Av"); titles are compared with plain ones. */
export const plainTitle = (t) => String(t || '').replace(/[\u2018\u2019]/g, "'");

/** The dates checked against Hebcal's JSON (i=on) on 10 November 2026. */
export const VERIFIED = {
  yomtov: ['2026-09-12', '2026-09-13', '2026-09-21', '2026-09-26', '2026-10-03', '2027-04-22', '2027-04-28', '2027-06-11'],
  memorial: ['2026-10-05', '2027-05-04', '2027-05-11'],
  fast: ['2027-08-12'],
};

export const urlFor = (start, end) => `${API}?v=1&cfg=json&maj=on&mod=on&i=on&start=${start}&end=${end}`;

/** The three lists from Hebcal items ({ title, date, yomtov? }), sorted and without repeats. */
export function collect(items) {
  const yomtov = new Set(); const memorial = new Set(); const fast = new Set();
  for (const it of items) {
    const day = String(it.date || '').slice(0, 10);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(day)) continue;
    if (it.yomtov === true) yomtov.add(day);
    const title = plainTitle(it.title);
    if (MEMORIAL_TITLES.includes(title)) memorial.add(day);
    if (FAST_TITLES.includes(title)) fast.add(day);
  }
  const sorted = (s) => [...s].sort();
  return { yomtov: sorted(yomtov), memorial: sorted(memorial), fast: sorted(fast) };
}

/** Which verified dates the lists lack, as "list: date" strings (empty when all are there). */
export function missingVerified(lists) {
  return Object.entries(VERIFIED).flatMap(([k, dates]) => dates.filter((d) => !lists[k].includes(d)).map((d) => `${k}: ${d}`));
}

const arr = (xs) => `[${xs.map((x) => `'${x}'`).join(', ')}]`;

/** The text of shared/restDays.js. */
export function render(lists, range) {
  return `// Generated by scripts/rest-days.mjs from Hebcal.com (CC BY 4.0). Do not edit by hand.
// Israeli schedule (i=on), ${range.from} to ${range.to}. To extend it: node madregot/scripts/rest-days.mjs
// Rest days (the streak skips them): Shabbat and Yom Tov. Quiet days (no reminders) add the national memorial days
// and Tish'a B'Av; those are never rest days, so the streak does not skip them.
// Weekdays are taken at UTC noon, so the browser and the Worker agree on the day of the week.

/** Yom Tov in Israel (Hebcal items with yomtov: true). */
export const YOMTOV_IL = ${arr(lists.yomtov)};
/** Swords of Iron War Memorial Day, Yom HaShoah, Yom HaZikaron. */
export const MEMORIAL_IL = ${arr(lists.memorial)};
/** Tish'a B'Av (schools are on holiday; a mourning day). */
export const FAST_IL = ${arr(lists.fast)};
/** The dates this table covers. */
export const RANGE = { from: '${range.from}', to: '${range.to}' };

const nextDay = (key) => { const d = new Date(\`\${key}T12:00:00Z\`); d.setUTCDate(d.getUTCDate() + 1); return d.toISOString().slice(0, 10); };
export const isYomTov = (key) => YOMTOV_IL.includes(key);
export const isRestDay = (key) => new Date(\`\${key}T12:00:00Z\`).getUTCDay() === 6 || isYomTov(key);
export const isQuietDay = (key) => isRestDay(key) || MEMORIAL_IL.includes(key) || FAST_IL.includes(key);
/** The day before a rest day (the streak and the week strip use this). */
export const isEve = (key) => isRestDay(nextDay(key)) && !isRestDay(key);
/** The day before a quiet day (reminders: memorial days also begin at sundown). */
export const isQuietEve = (key) => isQuietDay(nextDay(key)) && !isQuietDay(key);
`;
}

async function main() {
  const check = process.argv.includes('--check');
  const items = [];
  for (let y = FIRST_YEAR; y < FIRST_YEAR + YEARS; y += 1) {
    const url = urlFor(`${y}-09-01`, `${y + 1}-08-31`);
    const res = await fetch(url, { headers: { Accept: 'application/json' } });
    if (!res.ok) throw new Error(`Hebcal answered ${res.status} for ${url}`);
    const body = await res.json();
    if (!Array.isArray(body.items)) throw new Error(`Hebcal's answer for ${url} has no items`);
    items.push(...body.items);
    console.log(`${y}-${y + 1}: ${body.items.length} items`);
  }
  const lists = collect(items);
  const missing = missingVerified(lists);
  if (missing.length) {
    const near = (d) => items.filter((it) => String(it.date).startsWith(d)).map((it) => it.title).join(', ') || 'nothing';
    throw new Error(`Hebcal's answer lacks verified dates: ${missing.join('; ')}.\n${missing.map((m) => { const d = m.split(': ')[1]; return `  on ${d}: ${near(d)}`; }).join('\n')}\nNothing was written.`);
  }
  const range = { from: `${FIRST_YEAR}-09-01`, to: `${FIRST_YEAR + YEARS}-08-31` };
  const text = render(lists, range);
  console.log(`Yom Tov ${lists.yomtov.length}, memorial ${lists.memorial.length}, Tish'a B'Av ${lists.fast.length}; ${range.from} to ${range.to}.`);
  if (check) { console.log(text); return; }
  const out = fileURLToPath(new URL('../shared/restDays.js', import.meta.url));
  writeFileSync(out, text);
  console.log(`Wrote ${out}. Run the web unit tests (npx vitest run src/lib/restDays.test.js) and commit it.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => { console.error(e.message || e); process.exit(1); });
}
