// Writes src/learn/challenges/meta.gen.ts: what the app has to know about the challenge track before a topic's tasks
// have loaded (the curriculum spec's CURRICULUM-6.2, the open work QA_DURABLE.md names for DURABLE-11). Per task: its id,
// topic, the stair it follows, its kind, title and minutes, and its mistake (misc) when it has one. The tasks' parts,
// stories and figures stay in their topic's file and load on demand (learn/challenges/index.ts ensureChallenge), so
// the first download does not grow with every new task.
//
// It reads every learn/challenges/<topic>.ts (through Vite, so the files run as the app runs them) and keeps the
// arrays of tasks they export, in TOPIC_ORDER and then in each file's own order. npm run build runs it first, and
// learn/challenges.test.ts fails when the file in the repository is not what it would write.
//
// Usage: node scripts/gen-challenge-meta.mjs           write the file (only when it changed)
//        node scripts/gen-challenge-meta.mjs --check   exit 1 when the file is stale
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { basename, join } from 'node:path';

const WEB = fileURLToPath(new URL('..', import.meta.url));
const DIR = join(WEB, 'src/learn/challenges');
export const META_FILE = join(DIR, 'meta.gen.ts');
/** Files in learn/challenges that hold no tasks: the registry, the grading rules, and what this script writes. */
const SKIP = new Set(['index.ts', 'grade.ts', 'meta.gen.ts']);
/** The fields of a task that every screen reads before its topic has loaded. */
export const META_KEYS = ['id', 'topic', 'after', 'kind', 'title', 'minutes', 'misc'];

const isTask = (x) => !!x && typeof x === 'object' && typeof x.id === 'string' && typeof x.after === 'string' && Array.isArray(x.parts);

/**
 * The meta from the topic modules ({ file name: module namespace }) in the order of `topicOrder`: a topic's tasks in
 * its file's own order. A file holds the tasks of its own topic only, and an id is used once.
 */
export function collectMeta(modules, topicOrder) {
  const byTopic = new Map();
  const seen = new Set();
  for (const file of Object.keys(modules).sort()) {
    const topic = basename(file).replace(/\.ts$/, '');
    const mod = modules[file];
    const tasks = Object.keys(mod).sort().map((k) => mod[k]).filter((v) => Array.isArray(v) && v.length && v.every(isTask)).flat();
    for (const t of tasks) {
      if (t.topic !== topic) throw new Error(`${basename(file)}: ${t.id} is a task of ${t.topic}`);
      if (seen.has(t.id)) throw new Error(`${basename(file)}: two tasks are called ${t.id}`);
      seen.add(t.id);
    }
    if (tasks.length) byTopic.set(topic, tasks);
  }
  for (const topic of byTopic.keys()) if (!topicOrder.includes(topic)) throw new Error(`${topic}: not in TOPIC_ORDER`);
  return topicOrder.filter((tp) => byTopic.has(tp)).flatMap((tp) => byTopic.get(tp))
    .map((t) => Object.fromEntries(META_KEYS.filter((k) => t[k] !== undefined).map((k) => [k, t[k]])));
}

/** The file's text. */
export function renderMeta(meta) {
  return [
    '// GENERATED by scripts/gen-challenge-meta.mjs from learn/challenges/<topic>.ts. Do not edit: npm run build writes it',
    '// again, and learn/challenges.test.ts fails when it is stale. What every screen knows about a challenge task before',
    "// its topic's tasks have loaded: id, topic, the stair it follows, kind, title, minutes and its mistake (misc).",
    "import type { ChallengeMeta } from '../types';",
    '',
    // one task a line, so a new task is one new line
    `export const CHALLENGE_META: ChallengeMeta[] = [\n${meta.map((t) => `  ${JSON.stringify(t)},\n`).join('')}];`,
    '',
  ].join('\n');
}

/** Load every topic file through Vite (TypeScript, the @ alias) and render the meta. */
export async function generate() {
  const { createServer } = await import('vite');
  const server = await createServer({
    configFile: false, root: WEB, logLevel: 'error', appType: 'custom',
    server: { middlewareMode: true, hmr: false, watch: null, ws: false },
    optimizeDeps: { noDiscovery: true, include: [] },
    resolve: { alias: { '@': join(WEB, 'src'), '@shared': join(WEB, '../shared') } },
  });
  try {
    const { TOPIC_ORDER } = await server.ssrLoadModule('/src/learn/skills.ts');
    const modules = {};
    for (const name of readdirSync(DIR).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts') && !SKIP.has(f))) {
      modules[name] = await server.ssrLoadModule(`/src/learn/challenges/${name}`);
    }
    return renderMeta(collectMeta(modules, TOPIC_ORDER));
  } finally {
    await server.close();
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await generate();
  const old = existsSync(META_FILE) ? readFileSync(META_FILE, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (old !== text) { console.error('learn/challenges/meta.gen.ts is stale: run node scripts/gen-challenge-meta.mjs'); process.exit(1); }
    console.log('learn/challenges/meta.gen.ts is up to date');
  } else if (old !== text) {
    writeFileSync(META_FILE, text);
    console.log('wrote learn/challenges/meta.gen.ts');
  } else console.log('learn/challenges/meta.gen.ts is up to date');
}
