// Writes src/content/topics.gen.js and src/learn/challenges/meta.gen.ts (COUNCIL2-14): what the app has to know about
// each topic before its exercise generators have loaded, and about each challenge task before its parts have loaded.
//
// topics.gen.js: per topic, everything but the generators themselves: its id, grade, title, colour and description,
// its stairs' titles, its misconception names, its lesson, and its flags (placement, alsoFor, bridge). The generators
// (each stair's gen) stay in src/content/*.js and load per topic, on demand (content/index.js loadGens).
//
// It reads GRADE7 and GRADE8 (through Vite, as the app runs them) and keeps every value that is not a function.
//
// learn/challenges/meta.gen.ts: per challenge task, in CHALLENGES' order, its id, topic, stair (after), kind, title and
// minutes: what the map's next step (learn/next.ts, learn/challenges/open.ts) needs to offer one. The parts, the story
// and the figure stay in learn/challenges/<topic>.ts, which load with the challenge screen.
//
// npm run build runs it first, and src/content/topic-split.test.js fails when a file in the repository is not what it
// would write (and when a stair's generator is missing or extra).
//
// Usage: node scripts/gen-topic-meta.mjs           write the files (only those that changed)
//        node scripts/gen-topic-meta.mjs --check   exit 1 when a file is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';

const WEB = fileURLToPath(new URL('..', import.meta.url));
export const TOPIC_META_FILE = join(WEB, 'src/content/topics.gen.js');
export const CHALLENGE_META_FILE = join(WEB, 'src/learn/challenges/meta.gen.ts');
/** What a challenge task says before its file has loaded. */
export const CHALLENGE_KEYS = ['id', 'topic', 'after', 'kind', 'title', 'minutes'];

/** A topic without its functions: the same keys in the same order, a stair as { title } (and any other plain value). */
export function stripTopic(t) {
  const plain = (v) => (Array.isArray(v) ? v.map(plain) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).filter(([, x]) => typeof x !== 'function').map(([k, x]) => [k, plain(x)])) : v);
  return plain(t);
}

/** The file's text, from the topics in their order (GRADE7, then GRADE8). */
export function renderTopicMeta(topics) {
  return [
    '// GENERATED by scripts/gen-topic-meta.mjs from content/grade7.js and content/grade8.js. Do not edit: npm run build',
    '// writes it again, and content/topic-split.test.js fails when it is stale. What every screen knows about a topic',
    "// before its exercise generators have loaded (COUNCIL2-14): everything but each stair's gen, which content/index.js",
    '// loads per topic (loadGens).',
    `export const TOPIC_META = ${JSON.stringify(topics.map(stripTopic), null, 2)};`,
    '',
  ].join('\n');
}

/** The challenges' file, from CHALLENGES in its order. */
export function renderChallengeMeta(tasks) {
  return [
    '// GENERATED by scripts/gen-topic-meta.mjs from learn/challenges/index.ts. Do not edit: npm run build writes it again,',
    "// and content/topic-split.test.js fails when it is stale. What the map's next step knows about each challenge task",
    "// before the tasks' parts have loaded (COUNCIL2-14): learn/challenges/open.ts reads it.",
    "import type { ChallengeKind, SkillId, TopicId } from '../types';",
    '',
    'export interface ChallengeMeta { id: string; topic: TopicId; after: SkillId; kind: ChallengeKind; title: string; minutes: number }',
    `export const CHALLENGE_META: ChallengeMeta[] = ${JSON.stringify(tasks.map((t) => Object.fromEntries(CHALLENGE_KEYS.map((k) => [k, t[k]]))), null, 2)};`,
    '',
  ].join('\n');
}

/** Load the grade files and the challenges through Vite (the @ alias, the TypeScript they reach) and render both files. */
export async function generate() {
  const { createServer } = await import('vite');
  const server = await createServer({
    configFile: false, root: WEB, logLevel: 'error', appType: 'custom',
    server: { middlewareMode: true, hmr: false, watch: null, ws: false },
    optimizeDeps: { noDiscovery: true, include: [] },
    resolve: { alias: { '@': join(WEB, 'src'), '@shared': join(WEB, '../shared') } },
  });
  try {
    const g7 = await server.ssrLoadModule('/src/content/grade7.js');
    const g8 = await server.ssrLoadModule('/src/content/grade8.js');
    const ch = await server.ssrLoadModule('/src/learn/challenges/index.ts');
    return { [TOPIC_META_FILE]: renderTopicMeta([...g7.GRADE7, ...g8.GRADE8]), [CHALLENGE_META_FILE]: renderChallengeMeta(ch.CHALLENGES) };
  } finally {
    await server.close();
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const files = await generate();
  let stale = false;
  for (const [file, text] of Object.entries(files)) {
    const name = file.slice(join(WEB, 'src/').length);
    const old = existsSync(file) ? readFileSync(file, 'utf8') : '';
    if (old === text) { console.log(`${name} is up to date`); continue; }
    if (process.argv.includes('--check')) { console.error(`${name} is stale: run node scripts/gen-topic-meta.mjs`); stale = true; continue; }
    writeFileSync(file, text);
    console.log(`wrote ${name}`);
  }
  if (stale) process.exit(1);
}
