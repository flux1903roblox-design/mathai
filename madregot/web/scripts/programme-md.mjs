// The documents that state what Madregot teaches, generated from the code (CURRICULUM-1 item 7):
//   madregot/PROGRAMME.md      both grades, unit by unit, against the Ministry's programme (hours, months, stairs, gaps)
//   madregot/store/counts.json the topic and stair counts that public text quotes (store/frames.cjs reads it), and each
//                              grade's coverage sentence, for the store listing to quote
// Nothing in them is typed by hand. Any change to the stairs (web/src/learn/skills.ts, a topic's titles) or to the
// programme (shared/programme.js) runs this again in the same commit; claims.test.ts fails while the files are stale.
//
//   npm run programme:md      writes both files (vite-node scripts/programme-md.mjs --write)
//   npm run programme:check   writes nothing; exits with 1 when a committed file differs from what the code gives
//
// It runs under vite-node (not plain node) because the stair titles come from the app's content, which is TypeScript
// behind the '@' alias. Importing it (the tests do) runs nothing: render() is pure.
import { ALL_SKILLS, isBridgeSkill } from '@/learn/skills';
import { TOPIC, TOPICS } from '@/content/index.js';
import { PROGRAMME, ROADMAP_NEXT, coverageOf, coverageSentence, monthsText, inSchoolOrder, GRADE_NAME } from '@/learn/programme';

const STATE_WORD = { yes: 'יש', part: 'חלקי', no: 'עוד לא' };
const GRADES = ['7', '8'];

/**
 * The counts public text may quote: the grades' own topics and their stairs. A bridge unit (the fractions floor) is a
 * repair below the programme, counted in neither, so "48 stairs in 9 topics" stays a true sentence.
 */
export const countsOf = () => ({ topics: TOPICS.filter((t) => !t.bridge).length, stairs: ALL_SKILLS.filter((s) => !isBridgeSkill(s)).length });

const cell = (s) => String(s).replace(/\|/g, '\\|');
const stairName = (id) => {
  const [topic, level] = id.split(':');
  const t = TOPIC[topic];
  return `${t?.levels[Number(level) - 1]?.title || id} (${t?.title || topic}, \`${id}\`)`;
};
const gapText = (u, p) => `${p.note || u.title}${p.later === ROADMAP_NEXT ? ' (מגיע בשלב הבא)' : ''}`;

function gradeSection(grade) {
  const c = coverageOf(grade);
  const rows = inSchoolOrder(c.units).map((u) => {
    const gaps = u.parts.filter((p) => !p.taught).map((p) => gapText(u, p));
    return `| ${u.id} | ${cell(u.title)} | ${monthsText(u.months)} | ${u.hours} | ${u.taught} | ${STATE_WORD[u.state]} | ${u.stairs.map(stairName).map(cell).join('<br>') || '—'} | ${gaps.map(cell).join('<br>') || '—'} |`;
  });
  return [
    `## כיתה ${GRADE_NAME[grade]}`,
    '',
    coverageSentence(grade, c),
    '',
    `המקור: [פריסת ההוראה של משרד החינוך, כיתה ${GRADE_NAME[grade]}, ${PROGRAMME.year}](${PROGRAMME.sources[grade]})`,
    '',
    '| # | יחידה | חודשים | שעות | מהן במדרגות | מצב | מה יש במדרגות | מה עוד לא |',
    '|---|---|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

/** Both generated files, as { 'PROGRAMME.md': text, 'store/counts.json': text } (paths from madregot/). */
export function render() {
  const counts = countsOf();
  const cov = Object.fromEntries(GRADES.map((g) => [g, coverageOf(g)]));
  const md = [
    '<!-- GENERATED by `npm run programme:md` (madregot/web/scripts/programme-md.mjs) from shared/programme.js and the',
    '     stairs in web/src/learn/skills.ts. Do not edit by hand: change the code and run it again. -->',
    '',
    `# מה לומדים במדרגות, לפי תוכנית משרד החינוך (${PROGRAMME.year})`,
    '',
    'הקובץ נוצר מהקוד ואין לערוך אותו ידנית. אותם מספרים מופיעים באפליקציה, בעמוד "מה לומדים במדרגות".',
    '',
    'לכל יחידה בתוכנית יש שעות לפי פריסת ההוראה של המשרד. חלק של יחידה נחשב כנלמד במדרגות רק כשכל המדרגות שלו קיימות באפליקציה.',
    'יחידה היא "יש" כשכל החלקים שלה במדרגות, "חלקי" כשרק חלק מהם, ו"עוד לא" כשאף אחד מהם עוד לא.',
    'השעות הן ההמלצה של המשרד; בכיתה זה יכול להשתנות.',
    '',
    '| כיתה | שעות במדרגות | שעות בתוכנית | אחוז |',
    '|---|---|---|---|',
    ...GRADES.map((g) => `| ${GRADE_NAME[g]} | ${cov[g].taught} | ${cov[g].hours} | ${cov[g].pct}% |`),
    '',
    `באפליקציה היום: ${counts.stairs} מדרגות ב־${counts.topics} נושאים.`,
    '',
    ...GRADES.map(gradeSection),
  ].join('\n');
  // the store listing (STUDENT-12) quotes these sentences, as the /programme page shows them, instead of typing a share
  const store = { ...counts, coverage: Object.fromEntries(GRADES.map((g) => [g, coverageSentence(g, cov[g])])) };
  return { 'PROGRAMME.md': md, 'store/counts.json': `${JSON.stringify(store, null, 2)}\n` };
}

const write = process.argv.includes('--write');
const check = process.argv.includes('--check');
if (write || check) {
  const fs = await import('node:fs');
  const path = await import('node:path');
  const { fileURLToPath } = await import('node:url');
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const stale = [];
  Object.entries(render()).forEach(([rel, text]) => {
    const file = path.join(root, rel);
    const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (now === text) return;
    stale.push(rel);
    if (write) fs.writeFileSync(file, text);
  });
  if (check && stale.length) { console.error(`out of date: ${stale.join(', ')} (run npm run programme:md)`); process.exit(1); }
  console.log(write ? (stale.length ? `wrote ${stale.join(', ')}` : 'up to date') : 'up to date');
}
