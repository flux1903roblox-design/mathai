// The tutor evaluation's cases come from the app's own content (ai spec AI-7 Design 1): each hand-written situation in
// worker/eval/case-specs.json becomes the full context the tutor would get, built by the same code a lesson uses (the
// stair's diagnostic model through modelItem, a generator's item through makeItem, and buildTutorContext). So the
// evaluation measures the tutor on exactly what production sends.
//
//   WRITE_EVAL_CASES=1 npx vitest run src/learn/evalCases.test.ts   writes worker/eval/cases.json
//   npx vitest run                                                   checks the committed file is what the app makes now
//
// A case fails loudly when its wrong answer no longer diagnoses as the spec expects: a content change can never turn a
// "one named mistake" case into an "unknown" case without someone looking. Synthetic data only: no student, no model.
