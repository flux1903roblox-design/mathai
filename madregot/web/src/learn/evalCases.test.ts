const SPECS = new URL('../../../worker/eval/case-specs.json', import.meta.url);
const CASES = new URL('../../../worker/eval/cases.json', import.meta.url);
/** A fixed moment, so the learner summary (and so the file) is the same on every run. */
const NOW = '2026-11-05T10:00:00.000Z';
const CATS = ['D1', 'D2', 'D3', 'D4', 'W1', 'W2', 'W3', 'R1', 'H1', 'P1', 'A2', 'X1'];
const SHAPES = ['full', 'lite', 'economy'];
const FIRST = ['misconception', 'ambiguous', 'slip', 'unknown'];
const ABOUT = 'Generated by web/src/learn/evalCases.test.ts from case-specs.json (WRITE_EVAL_CASES=1); do not edit by hand. Each case is the app context the tutor gets (ctx), the chat so far (messages) and what a good reply does (expect). Synthetic: no student data.';

type Spec = Record<string, any>;
const fail = (id: string, why: string): never => { throw new Error(`eval case ${id}: ${why}`); };

/** A generator's exercise by its key: makeItem draws with Math.random, so it is driven by a seeded stream until it matches. */
function genItem(skill: string, key: string, id: string) {
  const { topic, level } = parseSkill(skill);
  const spy = vi.spyOn(Math, 'random').mockImplementation(seeded(20261105));
  try {
    for (let i = 0; i < 60000; i += 1) {
      const it = makeItem(topic, level);
      if (it.key === key) return it;
    }
  } finally { spy.mockRestore(); }
  return fail(id, `the generator of ${skill} never made ${key}`);
}

/** The lesson's exercise for a spec: the stair's diagnostic (or transfer) model with the spec's params, or a generator item. */
function itemOf(s: Spec) {
  if (s.source === 'gen') return { item: genItem(s.skill, s.key, s.id), model: null };
  const c = contentOf(s.skill) || fail(s.id, `no content for ${s.skill}`);
  const model = (s.source === 'transfer' ? c.transfer : c.diag) || fail(s.id, `${s.skill} has no ${s.source} model`);
  return { item: modelItem(c, model, s.params, s.source), model };
}

/** A learning record that says what the spec says: recent answers right of asked, the teaching stages, open mistakes. */
function learnOf(s: Spec) {
  const L = s.learner || {};
  const [right, asked] = L.recent || [6, 10];
  const miscon: Record<string, any> = {};
  for (const [skill, mid, state] of L.open || []) miscon[`${skill}|${mid}`] = { skill, id: mid, score: 2, seen: [], state, at: NOW };
  if (!s.skill) return { skills: {}, miscon };
  // right answers spread evenly over the asked ones
  const attempts = Array.from({ length: asked }, (_, i) => ({ at: NOW, ok: Math.floor(((i + 1) * right) / asked) > Math.floor((i * right) / asked), independent: true, purpose: 'practice' }));
  const taught = Object.fromEntries((L.taught || ['A', 'B', 'C']).map((k: string) => [k, NOW]));
  return { skills: { [s.skill]: { attempts, taught } }, miscon };
}

/** What the app says about one answer, in the spec's words. */
function firstOf(a: any) {
  if (!a) return null;
  if (a.kind === 'misconception') return a.ambiguous || a.ids.length > 1 ? 'ambiguous' : 'misconception';
  return a.kind;
}

/** One spec → one case: { id, cat, kind, shapes, ctx, messages, expect, tags }. Throws on anything that does not hold. */
function buildCase(s: Spec) {
  const e = s.expect || fail(s.id, 'no expect');
  if (!CATS.includes(s.cat)) fail(s.id, `unknown category ${s.cat}`);
  if (s.kind !== 'explain' && s.kind !== 'chat') fail(s.id, `unknown kind ${s.kind}`);
  if (!Array.isArray(s.shapes) || !s.shapes.includes('full') || s.shapes.some((x: string) => !SHAPES.includes(x))) fail(s.id, 'shapes must include full, and only full, lite, economy');
  if (s.kind === 'chat' && (!s.messages?.length || s.messages.at(-1).role !== 'user')) fail(s.id, 'a chat case ends with the student\'s turn');
  if (!(e.maxWords > 0) || typeof e.describe !== 'string' || e.describe.length < 20) fail(s.id, 'expect needs maxWords and a describe line');

  let ctx: any; let others: { id: string, label: string }[] = [];
  if (s.surface === 'assistant') {
    ctx = buildTutorContext({ surface: 'assistant', grade: s.grade, learn: learnOf(s) });
  } else {
    const { item, model } = itemOf(s);
    const { topic, level } = parseSkill(s.skill);
    const wrong: number[] = s.wrong || [];
    const phase = s.phase || (wrong.length >= 2 ? 'reveal' : wrong.length ? 'retry' : 'answer');
    if ((phase === 'answer') !== (wrong.length === 0) || (phase === 'reveal' && wrong.length < 2)) fail(s.id, `phase ${phase} does not fit ${wrong.length} wrong answers`);
    const state = { kind: 'node', item, wrong, phase, hint: wrong.length > 0, helped: s.helped === true, cats: s.cats || {} };
    const last = wrong.length ? resultOf(item, wrong.at(-1)) : null;
    ctx = buildTutorContext({ surface: 'lesson', item, s: state, last, learn: learnOf(s), grade: TOPIC[topic].grade, now: NOW });
    // what the app said about each answer is what the spec expects, or the case is not the situation it claims to be
    const answers = ctx.tries.answers;
    answers.forEach((a: any, i: number) => {
      if (i === 0) {
        const got = firstOf(a);
        if (!FIRST.includes(e.first)) fail(s.id, `expect.first is ${e.first}`);
        if (got !== e.first) fail(s.id, `answer ${wrong[0]} diagnoses as ${got} (${(a.ids || []).join(', ') || a.slip || ''}), not ${e.first}`);
        if (e.first === 'misconception' && a.ids[0] !== e.diagnosis) fail(s.id, `answer ${wrong[0]} diagnoses as ${a.ids[0]}, not ${e.diagnosis}`);
        if (e.first === 'ambiguous' && [...a.ids].sort().join() !== [...e.candidates].sort().join()) fail(s.id, `answer ${wrong[0]} fits ${a.ids.join(', ')}, not ${e.candidates.join(', ')}`);
        if (e.first === 'slip' && a.slip !== e.slip) fail(s.id, `answer ${wrong[0]} is a ${a.slip} slip, not ${e.slip}`);
      } else if (a.kind !== 'unknown') {
        fail(s.id, `answer ${wrong[i]} should fit no known mistake, but is ${a.kind} ${(a.ids || []).join(', ')}`);
      }
    });
    if (!answers.length && e.first) fail(s.id, 'expect.first without a wrong answer');
    // the other mistakes the stair knows: what a reply must not name (the leaky stub names one of them)
    const named = new Set(answers[0]?.ids || []);
    const ids = model ? Object.keys(model.bugs) : (contentOf(s.skill)?.misconceptions || []).map((m: any) => m.id);
    others = ids.filter((x: string) => !named.has(x)).map((x: string) => ({ id: x, label: catLabel(topic, level, x) || x }));
    if (!ctx.item?.answer) fail(s.id, 'the exercise has no answer');
  }
  const policy = ctx.policy.answer;
  const want = s.surface === 'assistant' ? 'homework' : (s.phase === 'reveal' ? 'reveal' : 'withhold');
  if (policy !== want) fail(s.id, `policy ${policy}, expected ${want}`);
  if (e.candidate != null && !String(s.messages.at(-1).content).includes(String(e.candidate))) fail(s.id, `the student never names the candidate ${e.candidate}`);
  if (!normalizeContext(ctx)) fail(s.id, 'normalizeContext rejects the context');

  const first = ctx.tries?.answers?.[0];
  return {
    id: s.id, cat: s.cat, kind: s.kind, shapes: s.shapes, ctx, messages: s.messages || [],
    expect: {
      ...e,
      policy,
      withhold: policy === 'withhold',
      answer: ctx.item?.answer ?? null,
      ...(e.first === 'misconception' ? { label: first.labels[0] } : {}),
      ...(e.first === 'ambiguous' ? { labels: first.labels } : {}),
      others,
    },
    tags: s.tags || [],
  };
}

/** The whole file, one case per line so a change shows as a change to that case. */
function casesFile(specs: Spec[]) {
  const ids = new Set<string>();
  for (const s of specs) { if (ids.has(s.id)) fail(s.id, 'the id is used twice'); ids.add(s.id); }
  const cases = specs.map(buildCase);
  return `{\n "about": ${JSON.stringify(ABOUT)},\n "cases": [\n${cases.map((c) => `  ${JSON.stringify(c)}`).join(',\n')}\n ]\n}\n`;
}

const specs: Spec[] = JSON.parse(readFileSync(SPECS, 'utf8')).cases;
let built: ReturnType<typeof buildCase>[] | null = null;
/** Every case, built once (the first test builds them through casesFile, and fails with the spec's id when one does not hold). */
const allCases = () => (built ||= specs.map(buildCase));

describe('the evaluation cases are built from the app itself (ai spec AI-7)', () => {
  it('every spec builds, diagnoses as it says, and cases.json is exactly what the app makes now', () => {
    const text = casesFile(specs);
    // @ts-ignore: node's process (this test runs in node)
    if (globalThis.process?.env?.WRITE_EVAL_CASES === '1') writeFileSync(CASES, text);
    let committed = '';
    try { committed = readFileSync(CASES, 'utf8'); } catch { /* missing: fails below */ }
    expect(committed === text, 'worker/eval/cases.json is out of date: run WRITE_EVAL_CASES=1 npx vitest run src/learn/evalCases.test.ts, read the diff, and commit it').toBe(true);
  });

  it('the categories and shapes have at least the planned rows (Design 2): 34 explain, 40 chat, 20 lite, 10 economy', () => {
    // at least: a new topic adds its own D1 rows (the curriculum lane), and the test below asks for them
    const count = (f: (s: Spec) => boolean) => specs.filter(f).length;
    const PLAN: Record<string, number> = { D1: 24, D2: 4, D3: 3, D4: 3, W1: 8, W2: 8, W3: 4, R1: 3, H1: 6, P1: 5, A2: 4, X1: 2 };
    for (const c of CATS) expect(count((s) => s.cat === c), c).toBeGreaterThanOrEqual(PLAN[c]);
    expect(count((s) => s.kind === 'explain')).toBeGreaterThanOrEqual(34);
    expect(count((s) => s.kind === 'chat')).toBeGreaterThanOrEqual(40);
    expect(count((s) => s.shapes.includes('lite') && s.cat === 'D1')).toBeGreaterThanOrEqual(10);
    expect(count((s) => s.shapes.includes('lite') && ['W1', 'W2'].includes(s.cat))).toBeGreaterThanOrEqual(6);
    expect(count((s) => s.shapes.includes('lite') && s.cat === 'A2')).toBeGreaterThanOrEqual(4);
    expect(count((s) => s.shapes.includes('economy') && s.cat === 'D1')).toBeGreaterThanOrEqual(6);
    expect(count((s) => s.shapes.includes('economy') && ['W1', 'W2'].includes(s.cat))).toBeGreaterThanOrEqual(4);
  });

  it('D1 covers every topic, and every algebra topic at least twice', () => {
    const topics = specs.filter((s) => s.cat === 'D1').map((s) => parseSkill(s.skill).topic);
    for (const t of Object.keys(TOPIC)) expect(topics.filter((x) => x === t).length, t).toBeGreaterThanOrEqual(['expr', 'eq', 'sys'].includes(t) ? 2 : 1);
  });

  it('the guard is tested where it matters: every withhold case renders WITHHOLD and its diagnosis line', () => {
    for (const c of allCases()) {
      const s = specs.find((x) => x.id === c.id)!;
      const text = renderContext(c.ctx);
      if (c.expect.withhold) expect(text, s.id).toContain('Final-answer policy: WITHHOLD');
      if (s.cat === 'D1') expect(text, s.id).toContain(`App diagnosis of answer (1): one mistake, ${s.expect.diagnosis}, "${c.expect.label}".`);
    }
  });
});

// The eval's mathEquations grader (shared/verify.js) must read maths the way the app writes it: over every worked
// solution, hint and stair text the app can show, it finds no false equation (the math judge found 0 in 53,694 pairs).
// A false alarm here would mark a correct tutor reply as wrong.
describe('checkEquations agrees with the app\'s own maths', () => {
  it('every equation in every stair\'s solutions, hints and texts, diagnostic and generator items alike, checks true', () => {
    let checked = 0;
    const wrong: string[] = [];
    const look = (where: string, lines: unknown[]) => {
      for (const l of lines) {
        if (typeof l !== 'string') continue;
        const r: { checked: number, wrong: any[] } = checkEquations(l);
        checked += r.checked;
        for (const w of r.wrong) wrong.push(`${where}: ${l} (${w.left} ${w.rel} ${w.right})`);
      }
    };
    for (const skill of ALL_SKILLS) {
      const c = contentOf(skill);
      const rnd = seeded(3);
      if (c) {
        for (const m of [c.diag, c.transfer]) {
          if (!m) continue;
          for (let i = 0; i < 25; i += 1) { const it = modelItem(c, m, m.params(rnd), 'diag'); look(skill, [...it.solution, it.hint]); }
        }
        look(`${skill} texts`, [c.idea, ...(c.why || []), ...(c.alt || []), ...c.misconceptions.flatMap((m: any) => [m.cause, ...(m.explain || [])])]);
      }
      const { topic, level } = parseSkill(skill);
      const spy = vi.spyOn(Math, 'random').mockImplementation(seeded(9));
      try { for (let i = 0; i < 25; i += 1) { const it = makeItem(topic, level); look(`${skill} generator`, [...(it.solution || []), it.hint]); } } finally { spy.mockRestore(); }
    }
    expect(wrong.slice(0, 10)).toEqual([]);
    expect(checked).toBeGreaterThan(4000);
  });
});
