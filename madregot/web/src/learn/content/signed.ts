/** A permutation of a small list, from the seeded source (so a question can be reproduced). */
const mix = <X>(arr: X[], rnd: () => number): X[] => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i -= 1) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
};
