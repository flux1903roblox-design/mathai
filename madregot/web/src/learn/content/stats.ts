const midrange = (a: number[]) => (Math.min(...a) + Math.max(...a)) / 2;

const meanModel: DiagModel<ListP> = {
  // four to six values; the mean has at most one decimal (a mean a student writes exactly)
  params: (rnd) => {
    for (;;) {
      const n = rint(rnd, 4, 6);
      const list = Array.from({ length: n }, () => rint(rnd, 2, 20));
      if (!clean(total(list) / n, 1)) continue;
      return { list };
    }
  },
  text: (p) => `מה הממוצע של הנתונים ${listMath(p.list)}?`,
  answer: (p) => total(p.list) / p.list.length,
  bugs: {
    // added, and stopped at the sum
    'no-divide': (p) => total(p.list),
    // put in order and took the middle
    'median-not-mean': (p) => medianOf(p.list),
    // halfway between the smallest and the largest, ignoring the values between them
    midrange: (p) => midrange(p.list),
  },
  solution: (p) => {
    const S = total(p.list); const n = p.list.length;
    return [`מחברים את כל הנתונים: $${p.list.join(' + ')} = ${S}$.`, `מחלקים במספר הנתונים, $${n}$: $${S} : ${n} = ${D(S / n)}$.`];
  },
  hint: () => 'מחברים את כל הנתונים ומחלקים במספר הנתונים: כאילו מיישרים את כל העמודות לאותו גובה.',
};

