const unsortedMid = (a: number[]) => { const n = a.length; return n % 2 ? a[(n - 1) / 2] : (a[n / 2 - 1] + a[n / 2]) / 2; };

const medianModel: DiagModel<ListP> = {
  // five to nine values, odd and even counts; the middle of the list as written is never the median
  params: (rnd) => {
    for (;;) {
      const n = rpick(rnd, [5, 6, 7, 8, 9]);
      const list = Array.from({ length: n }, () => rint(rnd, 1, 20));
      if (unsortedMid(list) === medianOf(list)) continue;
      return { list };
    }
  },
  text: (p) => `מה החציון של הנתונים ${listMath(p.list)}?`,
  answer: (p) => medianOf(p.list),
  bugs: {
    // the middle of the list as it was written
    unsorted: (p) => unsortedMid(p.list),
    // added and divided: the mean (only when it is a number a student can type exactly)
    'mean-not-median': (p) => orNull(total(p.list) / p.list.length),
    // even count: took the lower of the two middle values instead of the point between them
    'one-middle': (p) => (p.list.length % 2 ? null : sortNum(p.list)[p.list.length / 2 - 1]),
    // found the middle place, (n + 1) / 2, and wrote the place instead of the value there
    'median-position': (p) => (p.list.length + 1) / 2,
  },
  solution: (p) => {
    const s = sortNum(p.list); const n = s.length; const med = medianOf(p.list);
    const out = [`מסדרים מהקטן לגדול: $${listTex(s)}$.`];
    if (n % 2) out.push(`יש $${n}$ נתונים, מספר אי־זוגי. האמצעי עומד במקום ה־$${(n + 1) / 2}$, ומכל צד שלו $${(n - 1) / 2}$ נתונים.`, `החציון: $${med}$.`);
    else out.push(`יש $${n}$ נתונים, מספר זוגי. באמצע עומדים שניים: $${s[n / 2 - 1]}$ ו־$${s[n / 2]}$.`, `החציון הוא הממוצע שלהם: $\\frac{${s[n / 2 - 1]} + ${s[n / 2]}}{2} = ${D(med)}$.`);
    return out;
  },
  hint: (p) => (p.list.length % 2
    ? 'מסדרים מהקטן לגדול. החציון הוא הנתון שבאמצע: מספר שווה של נתונים מכל צד שלו.'
    : 'מסדרים מהקטן לגדול. במספר זוגי של נתונים עומדים באמצע שניים, והחציון הוא הממוצע שלהם.'),
};

