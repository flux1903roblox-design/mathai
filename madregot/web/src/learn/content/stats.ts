// Statistics (סטטיסטיקה), grade 8. The data are things to move: values pile up on a line (the mode is the tallest
// pile), are put in order (the median stands in the middle), and are levelled like bars (the mean is the fair share).
// A frequency table is a short way of writing a list, and a missing value is what the total still lacks.
import type { DiagModel, StairContent } from '../types';
import { rint, rpick } from '../expr';
// @ts-ignore: plain JS helpers shared with the exercise generators
import { T } from '@/content/util.js';

// ---------------------------------------------------------------- helpers

const total = (a: number[]) => a.reduce((t, v) => t + v, 0);
const sortNum = (a: number[]) => [...a].sort((x, y) => x - y);
const medianOf = (a: number[]) => { const s = sortNum(a); const n = s.length; return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2; };
const countOf = (a: number[], v: number) => a.filter((x) => x === v).length;
const modeOf = (a: number[]) => a.reduce((best, v) => (countOf(a, v) > countOf(a, best) ? v : best), a[0]);
/** A value a student can type exactly: at most `d` decimals (a mean of 25/3 cannot be predicted to the digit). */
const clean = (x: number, d = 2) => Math.abs(Math.round(x * 10 ** d) / 10 ** d - x) < 1e-9;
const orNull = (x: number) => (clean(x) ? x : null);
/** A number as a short decimal (a mean of 8.25 reads 8.25, as the student types it). */
const D = (x: number) => String(Math.round(x * 100) / 100);
const shuffle = <V>(a: V[], rnd: () => number) => { const b = [...a]; for (let i = b.length - 1; i > 0; i -= 1) { const j = Math.floor(rnd() * (i + 1)); [b[i], b[j]] = [b[j], b[i]]; } return b; };
// A list inside a Hebrew sentence: one expression per number inside a left-to-right isolate, so the numbers keep
// their order and a narrow screen can wrap between them (as in content/grade8.js).
const listMath = (a: number[]) => `⁦${a.map((v) => `$${T(v)}$`).join(', ')}⁩`;
const listTex = (a: number[]) => a.map((v) => T(v)).join(',\\ ');
/** A frequency table as a TeX grid: the values on top, how many times each appears underneath. */
const grid = (vals: number[], freqs: number[]) => `\\begin{array}{|${'c|'.repeat(vals.length)}} \\hline ${vals.join(' & ')} \\\\ \\hline ${freqs.join(' & ')} \\\\ \\hline \\end{array}`;
const pins = (labels: number[], start: number[]) => ({ kind: 'pins' as const, min: 0, max: 10, labels: labels.map(String), start });

// ---------------------------------------------------------------- stair 1: the mode

type ListP = { list: number[] };

const modeModel: DiagModel<ListP> = {
  // 13 or 15 values; one repeats three times, every other value at most twice and at least two of them twice (a close
  // race); the largest is never the mode. A value picked from the list at random is the mode only about one time in
  // five, so a check is not passed by copying a number from the question (src/learn/guessing.test.ts)
  params: (rnd) => {
    for (;;) {
      const n = rpick(rnd, [13, 15]); const c = 3; const m = rint(rnd, 2, 14);
      const arr: number[] = Array(c).fill(m);
      while (arr.length < n) { const v = rint(rnd, 1, 15); if (v !== m && countOf(arr, v) < 2) arr.push(v); }
      const twice = [...new Set(arr)].filter((v) => countOf(arr, v) === 2).length;
      if (Math.max(...arr) === m || c === m || twice < 2) continue;
      return { list: shuffle(arr, rnd) };
    }
  },
  text: (p) => `מה השכיח של הנתונים ${listMath(p.list)}?`,
  answer: (p) => modeOf(p.list),
  bugs: {
    // the biggest value, as if the mode were "the most" in size
    'mode-max': (p) => Math.max(...p.list),
    // the count that won, not the value that won
    'mode-count': (p) => countOf(p.list, modeOf(p.list)),
    // the middle value (the median), another "centre"
    'mode-median': (p) => medianOf(p.list),
  },
  solution: (p) => {
    const m = modeOf(p.list);
    return [
      `מסדרים מהקטן לגדול, כדי שערכים שווים יעמדו יחד: $${listTex(sortNum(p.list))}$.`,
      `$${m}$ מופיע $${countOf(p.list, m)}$ פעמים, יותר מכל ערך אחר.`,
      `השכיח הוא הערך עצמו: $${m}$.`,
    ];
  },
  hint: () => 'השכיח הוא הערך שמופיע הכי הרבה פעמים. סדרו את הנתונים כדי שערכים שווים יעמדו יחד, וספרו כל קבוצה.',
};

type SalesP = { sizes: number[]; freqs: number[] };
const pairs = (f: number, s: number) => (f === 1 ? `זוג אחד במידה $${s}$` : `$${f}$ זוגות במידה $${s}$`);
const salesMode = (p: SalesP) => p.sizes[p.freqs.indexOf(Math.max(...p.freqs))];

const salesModel: DiagModel<SalesP> = {
  // the counting is already done: how many pairs of each size were sold. The mode is a size, never a number of pairs.
  params: (rnd) => {
    for (;;) {
      const k = rint(rnd, 4, 6); const s0 = rint(rnd, 35, 39);
      const sizes = Array.from({ length: k }, (_, i) => s0 + i);
      const freqs = sizes.map(() => rint(rnd, 1, 12));
      const top = Math.max(...freqs);
      if (countOf(freqs, top) > 1 || freqs[k - 1] === top) continue;
      return { sizes, freqs };
    }
  },
  text: (p) => `חנות נעליים רשמה כמה זוגות נמכרו בשבוע אחד: ${p.sizes.map((s, i) => pairs(p.freqs[i], s)).join(', ')}. מה המידה השכיחה?`,
  answer: salesMode,
  bugs: {
    'mode-count': (p) => Math.max(...p.freqs),
    'mode-max': (p) => p.sizes[p.sizes.length - 1],
  },
  solution: (p) => {
    const m = salesMode(p); const f = Math.max(...p.freqs);
    return [`הכי הרבה זוגות נמכרו במידה $${m}$: $${f}$ זוגות, יותר מכל מידה אחרת.`, `השכיח הוא המידה $${m}$, ולא מספר הזוגות $${f}$.`];
  },
  hint: () => 'כאן הספירה כבר נעשתה: לכל מידה כתוב כמה זוגות נמכרו ממנה. איזו מידה נמכרה הכי הרבה פעמים?',
};

