/** Put the point of a drawn line at a given place (the shape predictPoint uses). */
const onLine = (m: number, b: number, label = 'P'): ManipSpec => ({ kind: 'plot', range: 6, label, start: null, line: { m, b } });
/** Build y = mx + b with the two handles (the shape buildLine uses), starting from another line. */
const builder = (m: number, b: number): ManipSpec => ({ kind: 'line', range: 6, start: { m, b } });
const nl = (from: number): ManipSpec => ({ kind: 'numberline', min: -10, max: 10, from, start: from });
const cell = (v: number | string) => (typeof v === 'number' ? T(v) : v);
/** A table of values as TeX: the x row over the y row. */
const tableTex = (xs: (number | string)[], ys: (number | string)[]) =>
  `\\begin{array}{c|${'c'.repeat(xs.length)}} x & ${xs.map(cell).join(' & ')} \\\\ \\hline y & ${ys.map(cell).join(' & ')} \\end{array}`;
/** The "+ b" after a product: " + 3", " - 3" or nothing. */
const plusB = (b: number) => (b === 0 ? '' : ` ${b < 0 ? '-' : '+'} ${Math.abs(b)}`);
/** p/q as written, then reduced when that reads differently: \frac{6}{4} = \frac{3}{2}. */
const fracEq = (p: number, q: number) => { const f = `\\frac{${p}}{${q}}`; const r = T(p / q); return f === r ? f : `${f} = ${r}`; };

// ================================================================ stair 1: a table of values

type Sub = { m: number; b: number; x: number };
const subTable = (p: Sub) => {
  const xs = [...[0, 1, 2, -1, 3].filter((v) => v !== p.x).slice(0, 3), p.x].sort((u, v) => u - v);
  return tableTex(xs, xs.map((v) => (v === p.x ? '?' : p.m * v + p.b)));
};
const substituteModel: DiagModel<Sub> = {
  // half the questions ask for a negative x: substituting it is where this stair is usually lost
  params: (rnd) => ({ m: rnz(rnd, -4, 4), b: rint(rnd, -6, 6), x: rnd() < 0.5 ? -rint(rnd, 1, 3) : rint(rnd, 1, 4) }),
  text: (p) => `בטבלת הערכים של $${lineTex(p.m, p.b)}$ חסר ערך אחד. מה $y$ כש־$x = ${T(p.x)}$?`,
  display: subTable,
  answer: (p) => p.m * p.x + p.b,
  bugs: {
    // multiplied and stopped: y = mx
    'forgot-b': (p) => (p.b !== 0 ? p.m * p.x : null),
    // the minus of x was lost: m·|x| + b
    'neg-sub': (p) => (p.x < 0 ? p.m * -p.x + p.b : null),
    // mx read as m + x
    'added-m': (p) => p.m + p.x + p.b,
  },
  solution: (p) => [
    `מציבים $${T(p.x)}$ במקום $x$${p.x < 0 ? ', בתוך סוגריים' : ''}: $y = ${T(p.m)} \\cdot ${T(p.x, true)}${plusB(p.b)}$.`,
    `כפל לפני חיבור: $${T(p.m)} \\cdot ${T(p.x, true)} = ${T(p.m * p.x)}$.`,
    p.b === 0 ? `$y = ${T(p.m * p.x)}$` : `$y = ${T(p.m * p.x)}${plusB(p.b)} = ${T(p.m * p.x + p.b)}$`,
  ],
  hint: (p) => (p.x < 0
    ? `מציבים את $${T(p.x)}$ עם הסימן שלו, בתוך סוגריים: $${T(p.m)} \\cdot ${T(p.x, true)}$. ואחרי הכפל לא שוכחים את $b$.`
    : 'מחליפים את $x$ במספר, כופלים ב־$m$, ורק אז מוסיפים את $b$.'),
};

type Grow = { k: number; s: number; m: number; b: number; n: number };
const growModel: DiagModel<Grow> = {
  // the same substitution in a price story, or a table that only shows its first columns
  params: (rnd) => (rnd() < 0.5
    ? { k: 0, s: rint(rnd, 0, 1), m: rint(rnd, 3, 12), b: 5 * rint(rnd, 1, 6), n: rint(rnd, 2, 9) }
    : { k: 1, s: 0, m: rnz(rnd, -5, 5), b: rnz(rnd, -5, 12), n: rint(rnd, 5, 9) }),
  text: (p) => (p.k === 1
    ? `זו טבלת ערכים של פונקציה קווית. מה $y$ כש־$x = ${p.n}$?`
    : p.s === 0
      ? `השכרת אופניים עולה $${p.b}$ שקלים על הקסדה ועוד $${p.m}$ שקלים לכל שעה. כמה עולות $${p.n}$ שעות?`
      : `חוג ציור גובה $${p.b}$ שקלים דמי הרשמה ועוד $${p.m}$ שקלים לכל שיעור. כמה עולים $${p.n}$ שיעורים?`),
  display: (p) => (p.k === 1 ? tableTex([0, 1, 2, '\\dots', p.n], [p.b, p.b + p.m, p.b + 2 * p.m, '', '?']) : ''),
  answer: (p) => p.m * p.n + p.b,
  bugs: {
    'forgot-b': (p) => p.m * p.n,
    // "one costs y(1), so n cost n times as much": the start is multiplied too
    proportional: (p) => (p.m + p.b) * p.n,
  },
  solution: (p) => (p.k === 1
    ? [
      `הצעד הקבוע: כל פעם ש־$x$ גדל ב־1, $y$ משתנה ב־$${T(p.m)}$.`,
      `ב־$x = 0$ מתחילים מ־$${T(p.b)}$, ועד $x = ${p.n}$ יש $${p.n}$ צעדים: $y = ${T(p.b)} + ${p.n} \\cdot ${T(p.m, true)} = ${T(p.m * p.n + p.b)}$.`,
    ]
    : [
      `פעם אחת משלמים $${p.b}$, ולכל ${p.s === 0 ? 'שעה' : 'שיעור'} עוד $${p.m}$: $y = ${p.m}x + ${p.b}$.`,
      `מציבים $x = ${p.n}$: $y = ${p.m} \\cdot ${p.n} + ${p.b} = ${p.m * p.n} + ${p.b} = ${p.m * p.n + p.b}$.`,
      `התשובה: $${p.m * p.n + p.b}$ שקלים.`,
    ]),
  hint: (p) => (p.k === 1
    ? 'בכמה $y$ משתנה בכל צעד? וכמה צעדים יש מ־$x = 0$ עד ה־$x$ המבוקש?'
    : 'מה משלמים פעם אחת, ומה משלמים שוב ושוב? רק את מה שחוזר כופלים.'),
};

