// The linear function (פונקציה קווית), grade 8, stairs 1–4. One picture runs through all four: a line is a
// staircase. A table of values climbs by the same step each time x grows by 1 (stair 1); that step is m and the
// value at x = 0 is b, built with the line builder (stair 2); on the grid the step is counted in squares, rise
// over run (stair 3); between two points it is the difference in y over the difference in x (stair 4).
import type { DiagModel, ManipSpec, StairContent } from '../types';
