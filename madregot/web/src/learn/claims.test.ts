// Every count of topics or stairs that a buyer can read is computed, never typed (CURRICULUM-1 item 7), and the
// generated documents are the ones the code gives today. When this fails after a change to the stairs or to
// shared/programme.js, run `npm run programme:md` (in madregot/web) and commit what it writes.
// The written claims match the code (curriculum stage 1, build-order step 8): a coverage sentence quoted in the docs is
// the one the page shows, and MADREGOT2.md's stairs table is the content's (it prints the row to paste when one differs).
import { describe, expect, it } from 'vitest';
import { ALL_SKILLS, isBridgeSkill } from './skills';
import { CONTENT } from './content/index';
import { coverageOf, coverageSentence, GRADE_NAME } from './programme';
import type { SkillId } from './types';
import { TOPICS } from '@/content/index.js';
import { render, countsOf } from '../../scripts/programme-md.mjs';
import programmeMd from '../../../PROGRAMME.md?raw';
import countsJson from '../../../store/counts.json?raw';

// the public text: the app's README and product docs, the store folder, and the page description
const DOCS: Record<string, string> = {
  ...import.meta.glob('../../../{README,PRODUCT,MADREGOT2}.md', { query: '?raw', import: 'default', eager: true }),
  ...import.meta.glob('../../../store/*.{md,cjs,json}', { query: '?raw', import: 'default', eager: true }),
  ...import.meta.glob('../../index.html', { query: '?raw', import: 'default', eager: true }),
};
// a glob key as a path from madregot/ ('../../../store/README.md' → 'store/README.md', '../../index.html' → 'web/index.html')
const name = (key: string) => (key.startsWith('../../../') ? key.slice(9) : `web/${key.slice(6)}`);

// a bridge unit (CURRICULUM-3's frac, bridge: true) is not one of the grade's topics, and its stairs are not counted
const STAIRS = ALL_SKILLS.filter((s) => !isBridgeSkill(s)).length;
const TOPIC_COUNT = (TOPICS as unknown as Array<{ bridge?: boolean }>).filter((t) => !t.bridge).length;
const COUNT = /(\d+)\s+(מדרגות|נושאים|stairs|topics)/g;

/** Every typed count in a text: [{ n, word, line }]. */
const countsIn = (text: string) => [...text.matchAll(COUNT)].map((m) => ({ n: Number(m[1]), word: m[2], line: text.slice(0, m.index).split('\n').length }));

describe('public counts of topics and stairs are the computed ones', () => {
  it('reads every file it promises to read', () => {
    const names = Object.keys(DOCS).map(name);
    ['README.md', 'PRODUCT.md', 'MADREGOT2.md', 'store/README.md', 'store/frames.cjs', 'store/counts.json', 'web/index.html']
      .forEach((f) => expect(names, f).toContain(f));
  });

  it('finds a typed count where there is one (the check is not empty)', () => {
    expect(countsIn('שישה נושאים, 33 מדרגות; 9 topics')).toEqual([{ n: 33, word: 'מדרגות', line: 1 }, { n: 9, word: 'topics', line: 1 }]);
  });

  it('every number before "מדרגות"/"stairs" is the number of stairs, and before "נושאים"/"topics" the number of topics', () => {
    const wrong = Object.entries(DOCS).flatMap(([key, text]) => countsIn(text)
      .filter(({ n, word }) => n !== (/מדרגות|stairs/.test(word) ? STAIRS : TOPIC_COUNT))
      .map(({ n, word, line }) => `${name(key)}:${line} says "${n} ${word}" (the app has ${STAIRS} stairs in ${TOPIC_COUNT} topics)`));
    expect(wrong).toEqual([]);
  });

  it('the store frame takes its counts from counts.json, which holds the computed ones', () => {
    expect(DOCS['../../../store/frames.cjs']).toContain("require('./counts.json')");
    const coverage = { '7': coverageSentence('7', coverageOf('7')), '8': coverageSentence('8', coverageOf('8')) };
    expect(JSON.parse(countsJson)).toEqual({ topics: TOPIC_COUNT, stairs: STAIRS, coverage });
    // the sentences are the /programme page's own (the store listing quotes them, never a share typed by hand)
    expect(coverage['7']).toMatch(/^במדרגות יש כבר את החומר של \d+ מתוך \d+ שעות ההוראה של כיתה ז׳ \(\d+%\)\.$/);
    expect(countsOf()).toEqual({ topics: TOPIC_COUNT, stairs: STAIRS });
  });
});

describe('the generated documents are up to date (npm run programme:md)', () => {
  const out = render();
  it('PROGRAMME.md is what the code gives', () => {
    expect(programmeMd).toBe(out['PROGRAMME.md']);
  });
  it('store/counts.json is what the code gives', () => {
    expect(countsJson).toBe(out['store/counts.json']);
  });
  it('PROGRAMME.md says it is generated, and names both grades and their sources', () => {
    expect(programmeMd.startsWith('<!-- GENERATED by `npm run programme:md`')).toBe(true);
    expect(programmeMd).toContain('## כיתה ז׳');
    expect(programmeMd).toContain('## כיתה ח׳');
    expect(programmeMd).toContain('prisa_7.pdf');
    expect(programmeMd).toContain('prisa_8.pdf');
  });
});

describe('a coverage sentence quoted in the docs is the one the code gives', () => {
  const SENTENCE = /במדרגות יש כבר את החומר של \d+ מתוך \d+ שעות ההוראה של כיתה (ז׳|ח׳) \(\d+%\)\./g;
  const GRADE_OF_NAME: Record<string, '7' | '8'> = { [GRADE_NAME['7']]: '7', [GRADE_NAME['8']]: '8' };
  // a doc may wrap a sentence over two lines: read it with its spaces folded
  const quoted = Object.entries(DOCS).flatMap(([key, text]) => [...text.replace(/\s+/g, ' ').matchAll(SENTENCE)]
    .map((m) => ({ file: name(key), said: m[0], grade: GRADE_OF_NAME[m[1]] })));

  it('finds the quotes it promises to check (the check is not empty)', () => {
    const where = (f: string) => quoted.filter((q) => q.file === f).map((q) => q.grade).sort();
    expect(where('README.md')).toEqual(['7', '8']);
    expect(where('MADREGOT2.md')).toEqual(['7', '8']);
  });

  it('every quoted sentence is coverageSentence() of today\'s stairs', () => {
    const wrong = quoted.map((q) => ({ ...q, now: coverageSentence(q.grade, coverageOf(q.grade)) }))
      .filter((q) => q.said !== q.now).map((q) => `${q.file} says "${q.said}", the code says "${q.now}"`);
    expect(wrong).toEqual([]);
  });
});

describe("MADREGOT2.md's stairs table is the content", () => {
  const doc = DOCS['../../../MADREGOT2.md'];
  /** The row the table should have for a stair, from its content (learn/content). */
  const rowOf = (skill: SkillId) => {
    const c = CONTENT[skill];
    const moved: string[] = [];
    c.discover.forEach((st) => { if (st.kind === 'explore' && !moved.includes(st.manip.kind)) moved.push(st.manip.kind); });
    const ids = c.misconceptions.map((m) => m.id);
    return [skill, c.title, `${c.discover.length}${moved.length ? ` (${moved.join(', ')})` : ''}`, String(c.examples.length),
      String(c.together.length), `${ids.length} (${ids.join(', ')})`, c.transfer ? 'yes' : 'no',
      `${isBridgeSkill(skill) ? 'יסודות; ' : ''}complete, tested`];
  };
  const cells = (line: string) => line.split('|').slice(1, -1).map((x) => x.trim());
  const rows = doc.split('\n').filter((l) => /^\| [a-z]+:\d+ \|/.test(l)).map(cells);

  it('lists every stair once, in the order of ALL_SKILLS, the floor\'s marked יסודות', () => {
    expect(rows.map((r) => r[0])).toEqual([...ALL_SKILLS]);
    expect(rows.filter((r) => r[7].includes('יסודות')).map((r) => r[0])).toEqual(ALL_SKILLS.filter(isBridgeSkill));
  });

  it('every row says what the stair\'s content has', () => {
    const wrong = rows.filter((r) => CONTENT[r[0] as SkillId] && r.join(' | ') !== rowOf(r[0] as SkillId).join(' | '))
      .map((r) => `MADREGOT2.md row ${r[0]} should be: | ${rowOf(r[0] as SkillId).join(' | ')} |`);
    expect(wrong).toEqual([]);
  });
});
