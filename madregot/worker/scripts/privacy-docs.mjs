// The database definitions document for the lawyer (COUNCIL2-7, COUNCIL2-3 code side): docs/privacy/DATABASE_DEFINITIONS.md,
// the "מסמך הגדרות מאגר" the Privacy Protection (Data Security) Regulations 2017 ask a database owner to keep. It is
// generated from worker/datamap.json (every D1 table, its columns, purpose, retention, recipients and purge, which
// test/datamap.test.js keeps true to schema.sql) and shared/retention.js (the purge's own numbers), so it cannot drift
// from the code: test/privacy-docs.test.js fails when the committed file differs from what this prints, or when a table
// or a column of the map is missing from it. The owner's business details stay blanks (______) for the owner to fill in
// the lawyer's copy; the document is a draft (טיוטה) until the lawyer has read it.
//
//   node scripts/privacy-docs.mjs --write   writes the file
//   node scripts/privacy-docs.mjs --check   writes nothing; exits 1 when the committed file is stale
//
// The data map's descriptions are kept in its own words (English), so nothing is retold by hand; the frame around them
// is Hebrew.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { RETENTION } from '../../shared/retention.js';

const ROOT = new URL('../../', import.meta.url);
export const OUT = 'docs/privacy/DATABASE_DEFINITIONS.md';
export const readMap = () => JSON.parse(readFileSync(new URL('worker/datamap.json', ROOT), 'utf8'));
/** shared/retention.js's own comments, by key: what each number is for, in the file's words. */
export function retentionNotes(src = readFileSync(new URL('shared/retention.js', ROOT), 'utf8')) {
  const out = {};
  // a number, or a sum of them (billingEventsDays: 7 * 365 + 2)
  for (const m of src.matchAll(/^\s*(\w+):\s*(\d[\d_ *+]*),\s*\/\/\s*(.+)$/gm)) out[m[1]] = m[3].trim();
  return out;
}

