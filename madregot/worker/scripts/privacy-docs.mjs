if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = new URL(OUT, ROOT);
  const text = render();
  if (process.argv.includes('--write')) { writeFileSync(out, text); console.log(`wrote ${OUT}`); }
  else {
    let now = '';
    try { now = readFileSync(out, 'utf8'); } catch { /* missing */ }
    if (now !== text) { console.error(`${OUT} is stale: run node worker/scripts/privacy-docs.mjs --write`); process.exit(1); }
    console.log(`${OUT} is up to date`);
  }
}
