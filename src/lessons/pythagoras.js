import PythagorasSquares, { hyp } from '@/components/learn/PythagorasSquares';
import { choice, numberQ } from './steps';

const pyth = ({ title, text, kind = 'check', goalC, solved, hint, explain }) => ({
  kind,
  title,
  text,
  widget: PythagorasSquares,
  config: {},
  init: { a: 2, b: 2 },
  ready: (v) => !!v.touched,
  check: goalC
    ? (v) => {
        const c = hyp(v);
        if (Math.abs(c - goalC) < 1e-9) return true;
        return { msg: c < goalC ? `היתר עכשיו קצר מדי ($c ≈ ${c.toFixed(2)}$). הגדל את הניצבים.` : `היתר עכשיו ארוך מדי ($c ≈ ${c.toFixed(2)}$).` };
      }
    : undefined,
  solve: solved ? (v) => ({ ...v, ...solved }) : undefined,
  hint,
  explain,
});

export default {
  id: 'pythagoras',
  title: 'משפט פיתגורס',
  subtitle: 'ריבועים שמסתתרים במשולש',
  minutes: 6,
  steps: [
    pyth({
      kind: 'explore',
      title: 'ריבועים על הצלעות',
      text: 'על כל צלע של המשולש ישר-הזווית בנינו **ריבוע**. המספר בכל ריבוע הוא השטח שלו.\n\nשנה את אורכי הניצבים $a$ ו-$b$ — והסתכל על **השטחים**.',
    }),
    choice({
      title: 'מה הקשר?',
      text: 'מה הקשר בין שטחי שלושת הריבועים?',
      options: [
        'הריבוע **הסגול** שווה לסכום **הצהוב** ו**הוורוד**',
        'הריבוע **הסגול** שווה למכפלה של שני האחרים',
        'אין קשר קבוע — זה משתנה',
      ],
      answer: 0,
      feedback: {
        1: 'נסה עם $a = 3, b = 4$: מכפלת השטחים היא $9 \\cdot 16 = 144$, אבל בסגול רואים 25.',
        2: 'בדוק כמה דוגמאות — משהו כן נשמר כל הזמן.',
      },
      explain: 'זה **משפט פיתגורס**: $a^2 + b^2 = c^2$. השטח של הריבוע על היתר שווה לסכום השטחים של הריבועים על הניצבים.',
    }),
    pyth({
      title: 'יתר של 5',
      text: '**המשימה:** בחר ניצבים שלמים כך שהיתר יהיה **בדיוק** $c = 5$.',
      goalC: 5,
      solved: { a: 3, b: 4 },
      hint: 'צריך ש-$a^2 + b^2 = 25$. אילו שני ריבועים מסתכמים ב-25?',
      explain: '$3^2 + 4^2 = 9 + 16 = 25 = 5^2$. השלישייה $(3, 4, 5)$ נקראת **שלשה פיתגורית**.',
    }),
    pyth({
      title: 'יתר של 10',
      text: '**המשימה:** ועכשיו יתר של **בדיוק** $c = 10$.',
      goalC: 10,
      solved: { a: 6, b: 8 },
      hint: 'מה קורה אם מכפילים את כל הצלעות של המשולש מהשלב הקודם ב-2?',
      explain: '$6^2 + 8^2 = 36 + 64 = 100 = 10^2$ — זה בדיוק המשולש $(3, 4, 5)$, מוגדל פי 2.',
    }),
    numberQ({
      title: 'מצא את היתר',
      text: 'הניצבים של משולש ישר-זווית הם $5$ ו-$12$. מה אורך היתר?',
      answer: 13,
      prefix: 'c =',
      hint: '$c = \\sqrt{5^2 + 12^2}$',
      feedback: (n) => (n === 17 ? 'חיברת את הצלעות עצמן — צריך לחבר את **הריבועים** שלהן.' : n === 169 ? 'זה $c^2$. עוד שורש אחד!' : null),
      explain: '$c = \\sqrt{25 + 144} = \\sqrt{169} = 13$',
    }),
    numberQ({
      title: 'מצא ניצב',
      text: 'היתר של משולש ישר-זווית הוא $10$ ואחד הניצבים הוא $6$. מה אורך הניצב השני?',
      answer: 8,
      prefix: 'b =',
      hint: 'הפעם מחסירים: $b^2 = c^2 - a^2$',
      explain: '$b = \\sqrt{100 - 36} = \\sqrt{64} = 8$',
    }),
    choice({
      title: 'גם בכיוון ההפוך',
      text: 'האם משולש עם צלעות $4$, $5$, $6$ הוא ישר-זווית?',
      options: ['כן', 'לא'],
      answer: 1,
      feedback: { 0: 'בדוק: האם סכום הריבועים של שתי הצלעות הקצרות שווה לריבוע של הארוכה?' },
      explain: '$4^2 + 5^2 = 16 + 25 = 41$, אבל $6^2 = 36$. מכיוון ש-$41 \\ne 36$ — המשולש **אינו** ישר-זווית.',
    }),
  ],
};
