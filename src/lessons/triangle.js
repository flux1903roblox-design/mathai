import TriangleAngles, { shownAngles } from '@/components/learn/TriangleAngles';
import { choice, numberQ } from './steps';

const START = [[60, 210], [300, 210], [140, 50]];

const tri = ({ title, text, kind = 'check', goal, solved, miss, hint, explain }) => ({
  kind,
  title,
  text,
  widget: TriangleAngles,
  config: {},
  init: { pts: START },
  ready: (v) => !!v.touched,
  check: goal ? (v) => (goal(shownAngles(v.pts)) ? true : { msg: miss }) : undefined,
  solve: solved ? (v) => ({ ...v, pts: solved }) : undefined,
  hint,
  explain,
});

export default {
  id: 'triangle-angles',
  title: 'סכום הזוויות במשולש',
  subtitle: 'גלה את הקסם של 180°',
  minutes: 5,
  steps: [
    tri({
      kind: 'explore',
      title: 'שחק עם המשולש',
      text: 'גרור את הקודקודים של המשולש לכל מקום שתרצה. הסתכל על שלוש הזוויות — **ועל הסכום שלהן** למטה.',
    }),
    choice({
      title: 'מה גילית?',
      text: 'סכום שלוש הזוויות במשולש הוא…',
      options: ['תלוי בצורת המשולש', 'תמיד $180°$', 'תמיד $360°$'],
      answer: 1,
      feedback: {
        0: 'נסה לחזור בראש למשולש: הזוויות השתנו, אבל הסכום?',
        2: '$360°$ זה סכום הזוויות במרובע. במשולש — חצי מזה.',
      },
      explain: 'בכל משולש $\\alpha + \\beta + \\gamma = 180°$. במניפה רואים את זה: שלוש הזוויות יחד תמיד ממלאות **חצי עיגול** — קו ישר.',
    }),
    tri({
      title: 'זווית ישרה',
      text: '**המשימה:** צור משולש ישר-זווית — שאחת הזוויות תהיה בדיוק $90°$. כשתצליח יופיע ריבוע קטן בפינה.',
      goal: (a) => a.includes(90),
      solved: [[60, 210], [300, 210], [60, 50]],
      miss: 'אף זווית עוד לא $90°$. נסה ליישר קודקוד אחד מעל קודקוד אחר.',
      hint: 'הזווית הישרה נוצרת כשצלע אחת **מאונכת** לאחרת — למשל צלע אופקית וצלע אנכית.',
      explain: 'יש! ובמשולש ישר-זווית שתי הזוויות האחרות מסתכמות יחד ב-$90°$.',
    }),
    tri({
      title: 'כולן שוות',
      text: '**המשימה:** צור משולש שבו **שלוש הזוויות שוות**.',
      goal: (a) => a.every((x) => x === 60),
      solved: [[80, 220], [280, 220], [180, 47]],
      miss: 'הזוויות עוד לא שוות. איזו זווית גדולה מדי? הזז את הקודקוד שלה.',
      hint: 'אם הסכום הוא $180°$ ויש שלוש זוויות שוות — כמה כל אחת?',
      explain: 'כל זווית היא $180° \\div 3 = 60°$. זה משולש **שווה-צלעות**.',
    }),
    numberQ({
      title: 'הזווית החסרה',
      text: 'במשולש יש זווית של $50°$ וזווית של $70°$. מהי הזווית השלישית?',
      answer: 60,
      suffix: '°',
      hint: 'כמה חסר ל-$50° + 70°$ כדי להגיע ל-$180°$?',
      explain: '$180° - 50° - 70° = 60°$',
    }),
    numberQ({
      title: 'משולש שווה-שוקיים',
      text: 'במשולש שווה-שוקיים זווית הראש היא $40°$. כמה מעלות יש בכל אחת מזוויות הבסיס?',
      answer: 70,
      suffix: '°',
      hint: 'שתי זוויות הבסיס **שוות**, ויחד עם זווית הראש הן $180°$.',
      feedback: (n) => (n === 140 ? 'זה סכום **שתי** זוויות הבסיס יחד. כמה לכל אחת?' : null),
      explain: '$(180° - 40°) \\div 2 = 140° \\div 2 = 70°$',
    }),
  ],
};
