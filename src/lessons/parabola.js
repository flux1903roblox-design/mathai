import ParabolaPlayground, { sameParabola } from '@/components/learn/ParabolaPlayground';
import { choice, numberQ } from './steps';

const para = ({ title, text, start, fixed = [], target, goal, solved, miss, hint, explain }) => ({
  kind: 'check',
  title,
  text,
  widget: ParabolaPlayground,
  config: { fixed, target },
  init: start,
  ready: (v) => !!v.touched,
  check: (v) => {
    if (target) {
      if (sameParabola(v, target)) return true;
      const vertexOk = v.h === target.h && v.k === target.k;
      if (vertexOk) return { msg: 'הקודקוד כבר במקום! עכשיו התאם את הצורה — בדוק את $a$.' };
      if (v.a === target.a) return { msg: 'הצורה נכונה, אבל הקודקוד לא במקום. כוון את $h$ ואת $k$.' };
      return { msg: 'עוד לא. התחל מלהזיז את הקודקוד הוורוד אל העיגול המקווקו.' };
    }
    return goal(v) ? true : { msg: miss };
  },
  solve: (v) => ({ ...v, ...(target || solved) }),
  hint,
  explain,
});

